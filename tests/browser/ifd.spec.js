const {test,expect}=require('@playwright/test');
test('IFD preview uses supplied curves and observed 3-hour accumulations, with both modes',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const data=await (await page.request.get('/api/rainfall')).json();
 const template=data.stations.find(s=>s.coordinates);
 data.stations=[{...template,values:[10,0,20,30,null,5,0,0]}];
 await page.route('**/api/rainfall*',route=>route.fulfill({json:data}));
 await page.goto('/');await page.locator('.station').click();
 await expect(page.locator('#ifdChart')).toBeVisible();
 await expect(page.locator('.ifd-provisional')).toContainText('confirmed by the table provider');
 let chart=await page.locator('#ifdChart').evaluate(c=>{const d=Chart.getChart(c).data.datasets;return {observed:d[0].data,design:d.find(d=>d.label==='1% AEP reference').data};});
 expect(chart.observed.map(p=>p.x)).toEqual([180,360,540,720,900,1080,1260,1440]);
 expect(chart.observed.map(p=>p.y)).toEqual([0,0,5,null,null,null,null,null]);
 expect(chart.design.find(p=>p.x===180).y).toBe(130.2);expect(chart.design[0].x).toBe(5);
 await page.locator('#ifdMode').selectOption('wettest');
 chart=await page.locator('#ifdChart').evaluate(c=>Chart.getChart(c).data.datasets[0].data);
 expect(chart[0].y).toBe(30);expect(chart[1].y).toBe(50);expect(chart[3].y).toBe(60);expect(chart[7].y).toBeNull();
 await expect(page.locator('#ifdComparison')).toContainText('true wettest accumulation may be higher');
 await expect(page.locator('#ifdComparison tbody tr')).toHaveCount(4);
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 expect(errors).toEqual([]);
});
test('missing or malformed reference keeps rainfall view usable',async({page})=>{
 await page.route('**/reference/brisbane-ifd-2030.csv',r=>r.fulfill({body:'not an IFD table'}));
 await page.goto('/');await page.locator('.station').first().click();
 await expect(page.locator('#hyetograph')).toBeVisible();
 await expect(page.locator('#ifdComparison')).toContainText('headings not recognised');
 await expect(page.locator('#ifdChart')).toHaveCount(0);
});
